import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const assets={};
for(const [name,type] of [['index.html','text/html'],['app.js','text/javascript'],['engine.js','text/javascript'],['worker.js','text/javascript'],['style.css','text/css']]) {
  assets['/'+name]={body:await readFile(path.join(root,'dist',name),'utf8'),type:type+'; charset=utf-8'};
}
const policies={};
for(const line of (await readFile(path.join(root,'dist/_headers'),'utf8')).split('\n')) {
  const match=line.match(/^\s+([^:]+):\s*(.+)$/);
  if(match) policies[match[1]]=match[2];
}
const source=`// Generated by scripts/build-worker.mjs. Do not edit.\nconst assets=${JSON.stringify(assets)};\nconst policies=${JSON.stringify(policies)};\nexport default { async fetch(request) {\n const headers=new Headers(policies);\n headers.set('Cache-Control','no-store');\n if (!['GET','HEAD'].includes(request.method)) { headers.set('Allow','GET, HEAD'); return new Response(null,{status:405,headers}); }\n const pathname=new URL(request.url).pathname;\n const asset=assets[pathname==='/'?'/index.html':pathname];\n if(!asset) { headers.set('Content-Type','text/plain; charset=utf-8'); return new Response(request.method==='HEAD'?null:'Not found',{status:404,headers}); }\n headers.set('Content-Type',asset.type);\n return new Response(request.method==='HEAD'?null:asset.body,{headers});\n}};\n`;
await mkdir(path.join(root,'dist/server'),{recursive:true});
await writeFile(path.join(root,'dist/server/index.js'),source);
try {
  const manifest=await readFile(path.join(root,'.openai/hosting.json'),'utf8');
  await mkdir(path.join(root,'dist/.openai'),{recursive:true});
  await writeFile(path.join(root,'dist/.openai/hosting.json'),manifest);
} catch(error) { if(error.code!=='ENOENT') throw error; }
console.log('Built dependency-free response wrapper with embedded assets and HTTP security headers.');
